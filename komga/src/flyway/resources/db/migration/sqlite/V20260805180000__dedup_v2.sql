-- Preserve the intent of already processed clusters. Only survivor pairs with content
-- evidence are migrated, while cover-only and explicitly unrelated pairs are not suppressed.
INSERT OR IGNORE INTO DEDUP_PAIR_DECISION
    (BOOK_LOW_ID, BOOK_HIGH_ID, DECISION, RESOLUTION_ID, ACTOR_ID, CREATED_DATE)
SELECT ML.BOOK_ID,
       MH.BOOK_ID,
       'KEEP_BOTH',
       RES.ID,
       COALESCE(RES.ACTOR_ID, 'system:migration'),
       COALESCE(C.PROCESSED_DATE, C.LAST_MODIFIED_DATE, CURRENT_TIMESTAMP)
FROM DEDUP_CLUSTER C
JOIN DEDUP_CLUSTER_MEMBER ML
  ON ML.CLUSTER_ID = C.ID AND ML.PRESENT = true
JOIN DEDUP_CLUSTER_MEMBER MH
  ON MH.CLUSTER_ID = C.ID AND MH.PRESENT = true AND ML.BOOK_ID < MH.BOOK_ID
JOIN BOOK BL
  ON BL.ID = ML.BOOK_ID AND BL.DELETED_DATE IS NULL
JOIN BOOK BH
  ON BH.ID = MH.BOOK_ID AND BH.DELETED_DATE IS NULL
JOIN DEDUP_RELATION R
  ON R.BOOK_LOW_ID = ML.BOOK_ID AND R.BOOK_HIGH_ID = MH.BOOK_ID
LEFT JOIN DEDUP_RESOLUTION RES
  ON RES.ID = C.LAST_RESOLUTION_ID
WHERE C.STATUS = 'PROCESSED'
  AND R.RELATION_TYPE <> 'UNRELATED';

