    FOREIGN KEY (BOOK_HIGH_ID) REFERENCES BOOK (ID) ON DELETE CASCADE,
    FOREIGN KEY (RESOLUTION_ID) REFERENCES DEDUP_RESOLUTION (ID) ON DELETE SET NULL
);

