UPDATE DEDUP_CLUSTER
SET MEMBER_COUNT = (
        SELECT COUNT(*) FROM DEDUP_CLUSTER_MEMBER M
        WHERE M.CLUSTER_ID = DEDUP_CLUSTER.ID AND M.PRESENT = true
    );

UPDATE DEDUP_CLUSTER
SET TOTAL_PAIR_COUNT = MEMBER_COUNT * (MEMBER_COUNT - 1) / 2;

UPDATE DEDUP_CLUSTER
SET VERIFIED_PAIR_COUNT = (
        SELECT COUNT(*)
        FROM DEDUP_RELATION R
        JOIN DEDUP_CLUSTER_MEMBER ML
          ON ML.CLUSTER_ID = DEDUP_CLUSTER.ID AND ML.BOOK_ID = R.BOOK_LOW_ID AND ML.PRESENT = true
        JOIN DEDUP_CLUSTER_MEMBER MH
          ON MH.CLUSTER_ID = DEDUP_CLUSTER.ID AND MH.BOOK_ID = R.BOOK_HIGH_ID AND MH.PRESENT = true
        WHERE R.STATUS = 'VERIFIED'
          AND R.RELATION_TYPE <> 'VISUALLY_SIMILAR'
          AND R.LOW_CONTENT_GENERATION = ML.SOURCE_CONTENT_GENERATION
          AND R.HIGH_CONTENT_GENERATION = MH.SOURCE_CONTENT_GENERATION
    );

UPDATE DEDUP_CLUSTER
SET EVIDENCE_MATURITY = CASE
        WHEN VERIFIED_PAIR_COUNT = 0 THEN 'COVER_ONLY'
        WHEN VERIFIED_PAIR_COUNT >= TOTAL_PAIR_COUNT THEN 'COMPLETE'
        ELSE 'PARTIAL'
    END;

UPDATE DEDUP_CLUSTER
SET REVISION = REVISION + 1,
    STATUS = 'UNPROCESSED',
    PROCESSED_REVISION = NULL,
    REOPEN_REASON = 'IDENTITY_RULE_CHANGED',
    PROCESSED_DATE = NULL,
    LAST_MODIFIED_DATE = CURRENT_TIMESTAMP
WHERE STATUS = 'PROCESSED';

