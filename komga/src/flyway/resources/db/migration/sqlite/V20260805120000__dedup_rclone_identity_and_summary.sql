    HIGH_CONTENT_GENERATION = 'dedup-v2:' || CAST((SELECT FILE_SIZE FROM BOOK WHERE BOOK.ID = DEDUP_RELATION.BOOK_HIGH_ID) AS varchar) || ':UNHASHED';

